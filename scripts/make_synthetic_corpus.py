    facts["estimated_cost"] = (f"Rs. {inr(value)}/-", ["estimated cost", f"Rs. {inr(value)}/-"])
    facts["fee"] = (f"Rs. {inr(fee)}/-", ["tender fee", f"Rs. {inr(fee)}/-"])
    facts["closing"] = (fmt_date(closes), ["last date", fmt_date(closes)])
    facts["completion"] = (f"{months} months", ["period of", f"{months} months", "completion"])
    facts["validity"] = (f"{validity} days", [f"{validity} days from the date of opening"])

