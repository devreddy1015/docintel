def render_pdf(html: str, out: Path, *, scan_pages: set[int] = frozenset()) -> int:
    archive = pymupdf.Archive(str(FONT_DIR))
    story = pymupdf.Story(html=f"<style>{CSS}</style>{html}", archive=archive)
    mediabox = pymupdf.paper_rect("a4")
    where = mediabox + (50, 60, -50, -60)
    writer = pymupdf.DocumentWriter(str(out))
    more = True
    while more:
        dev = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    # Footer on every page, then optionally rasterise some pages to simulate scans.
    doc = pymupdf.open(out)
    for page in doc:
        page.insert_text((50, mediabox.height - 30), NOTICE, fontsize=6.5, color=(0.45, 0.45, 0.45))
        page.insert_text(
            (mediabox.width - 90, mediabox.height - 30),
            f"Page {page.number + 1} of {doc.page_count}",
            fontsize=7,
        )
    if scan_pages:
        scanned = pymupdf.open()
        for page in doc:
            if page.number in scan_pages:
                pix = page.get_pixmap(dpi=200, colorspace=pymupdf.csGRAY)
                new = scanned.new_page(width=page.rect.width, height=page.rect.height)
                new.insert_image(new.rect, pixmap=pix)
            else:
                scanned.insert_pdf(doc, from_page=page.number, to_page=page.number)
        doc.close()
        scanned.save(out, garbage=3, deflate=True)
        scanned.close()
        return pymupdf.open(out).page_count
    n = doc.page_count
    doc.saveIncr()
    doc.close()
    return n


