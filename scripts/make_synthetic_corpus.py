def make_doc(t: dict, rng: random.Random) -> tuple[str, dict, list[str]]:
    """Returns (html, facts, sections_order). facts: name -> (answer text, evidence text)."""
    value, emd = float(t["value_inr"]), float(t["emd_inr"])
    closes = datetime.fromisoformat(t["closes_at"]).astimezone()
    published = datetime.fromisoformat(t["published_at"]).astimezone()
    months = rng.choice([3, 4, 6, 9, 12, 18])
    validity = rng.choice([90, 120, 180])
