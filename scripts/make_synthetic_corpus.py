    body = head
    if bilingual:
        body += f"<div class='hi'><p>{HINDI_INTRO}</p><p>{HINDI_EMD.format(emd=inr(emd), closes=closes.strftime('%d-%m-%Y'))}</p></div>"
    for i, (title, html) in enumerate(sections, start=1):
        body += f"<h2>{i}. {title}</h2>{html}"
