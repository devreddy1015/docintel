    pg_pct = rng.choice([3, 5])
    ld_week = rng.choice([0.5, 1])
    ld_max = rng.choice([5, 10])
    dlp = rng.choice([6, 12, 24])
    fee = rng.choice([500, 1000, 1180, 2000, 5000])
    works_rule = rng.choice([(3, 40), (2, 60), (1, 80)])
    turnover_pct = rng.choice([30, 50, 100])
    prebid = published + timedelta(days=rng.choice([4, 5, 7]))
    has_advance = rng.random() < 0.6
    advance_pct = rng.choice([5, 10])
    bilingual = rng.random() < 0.35
    officer = (t["buyer_raw"].split("||")[-1].strip()) or "Executive Engineer"

    works_amt = value * works_rule[1] / 100
    turnover_amt = value * turnover_pct / 100
    facts: dict[str, tuple[str, str]] = {}

