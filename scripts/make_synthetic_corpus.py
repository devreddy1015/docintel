def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=30)
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--tenderlens", default="http://localhost:8080")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "pdfs" / "synthetic")
    ap.add_argument("--eval", type=Path, default=ROOT / "data" / "eval")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    tenders = fetch_tenders(args.tenderlens, args.n, args.seed)
    args.out.mkdir(parents=True, exist_ok=True)
    args.eval.mkdir(parents=True, exist_ok=True)
    # Split by document: fine-tuning trains on one set of tenders and is measured on others.
    split = {
        t["source_tender_id"]: ("test" if i % 3 == 0 else "train") for i, t in enumerate(tenders)
    }
    questions, manifest = [], []
    for i, t in enumerate(tenders):
        html, meta, _ = make_doc(t, rng)
        tid = t["source_tender_id"]
        folder = args.out / tid
        folder.mkdir(exist_ok=True)
        out = folder / f"NIT_{tid}.pdf"
        scan = {1} if i % 10 == 4 else set()  # every 10th notice has a scanned page 2
        pages = render_pdf(html, out, scan_pages=scan)
        manifest.append(
            {
                "tender_id": tid,
                "file": str(out.relative_to(ROOT)),
                "pages": pages,
                "scanned_pages": sorted(p + 1 for p in scan),
                "bilingual": meta["bilingual"],
                "split": split[tid],
            }
        )
        for fact, (answer, evidence) in meta["facts"].items():
            q_eval, q_train = QUESTIONS[fact]
            work = " ".join(t["title"].split()[:9]).rstrip(",.;:")
            questions.append(
                {
                    "id": f"{tid}:{fact}",
                    "tender_id": tid,
                    "split": split[tid],
                    "fact": fact,
                    "question": q_eval,
                    "train_question": q_train,
                    "answerable": True,
                    # Same question, naming the work instead of being scoped to the tender.
                    "global_question": f"{q_eval.rstrip('?')} for “{work}”?",
                    "answer": answer,
                    "evidence": evidence,
                    "scanned": bool(scan),
                }
            )
        if not meta["has_advance"]:
            questions.append(
                {
                    "id": f"{tid}:advance_absent",
                    "tender_id": tid,
                    "split": split[tid],
                    "fact": "advance",
                    "question": QUESTIONS["advance"][0],
                    "answerable": False,
                    "answer": "",
                    "evidence": "",
                }
            )
        for j, q in enumerate(rng.sample(UNANSWERABLE, k=1)):
            questions.append(
                {
                    "id": f"{tid}:unanswerable{j}",
                    "tender_id": tid,
                    "split": split[tid],
                    "fact": "none",
                    "question": q,
                    "answerable": False,
                    "answer": "",
                    "evidence": "",
                }
            )
    (args.eval / "questions.jsonl").write_text(
        "".join(json.dumps(q, ensure_ascii=False) + "\n" for q in questions)
    )
    (args.eval / "corpus.json").write_text(json.dumps(manifest, indent=1))
    a = sum(q["answerable"] for q in questions)
    print(
        f"{len(tenders)} notices in {args.out}, {len(questions)} questions ({a} answerable, {len(questions) - a} not)"
    )


if __name__ == "__main__":
    main()
