"""Synthetic tender notices + an evaluation set, for development until real PDFs are added.

Each PDF is built from a REAL tender in TenderLens (its ID, title, buyer, value, EMD and
dates) plus generated clauses (eligibility, turnover, completion time, security deposit,
penalties, ...) and generic boilerplate full of distractor numbers. Every page carries a
"SYNTHETIC TEST DOCUMENT" notice. Because we generate the text, we know the right answer
and the chunk that holds it, which is what the evaluation needs.

Variety on purpose: clause wording varies, the question wording differs from the
document's (e.g. "bid security" vs "Earnest Money Deposit"), a third of the notices
have a Hindi paragraph, a few pages are rendered as images to exercise OCR, and some
facts are deliberately absent so that "I couldn't find this" is the right answer.

    uv run python scripts/make_synthetic_corpus.py --n 30
"""

