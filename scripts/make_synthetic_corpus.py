def inr(v: float) -> str:
    """Indian digit grouping: 4918700000 -> 4,91,87,00,000."""
    s = f"{int(round(v))}"
    if len(s) <= 3:
        return s
    head, tail = s[:-3], s[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join(parts) + "," + tail


def words_lakh(v: float) -> str:
    return f"{v / 1e7:.2f} crore" if v >= 1e7 else f"{v / 1e5:.2f} lakh"


def fmt_date(d: datetime) -> str:
    return d.strftime("%d-%b-%Y %I:%M %p")


def fetch_tenders(base: str, n: int, seed: int) -> list[dict]:
    rows = []
    with httpx.Client(base_url=base, timeout=30) as c:
        for sector in [
            "buildings",
            "roads",
            "electrical",
            "water",
            "it",
            "security",
            "health",
            "facility",
            "lab",
            "consultancy",
        ]:
            r = c.get(
                "/api/tenders", params={"sector": sector, "page_size": 40, "min_value": 500000}
            )
            r.raise_for_status()
            rows += [
                t
                for t in r.json()["results"]
                if t["value_inr"] and t["emd_inr"] and float(t["emd_inr"]) > 0
            ]
    rng = random.Random(seed)
    rng.shuffle(rows)
    seen, out = set(), []
    for t in rows:  # one tender per buyer keeps the corpus varied
        key = t["buyer_raw"]
        if key not in seen:
            seen.add(key)
            out.append(t)
        if len(out) == n:
            break
    return out


