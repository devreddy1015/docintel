from docintel.chunking import approx_tokens, chunk_pages, is_heading, sections
from docintel.extract import Page, garbled_devanagari


def test_headings():
    assert is_heading("ELIGIBILITY CRITERIA")
    assert is_heading("4.2 Financial turnover")
    assert is_heading("Annexure II")
    assert not is_heading(
        "The bidder shall deposit Earnest Money of Rs. 16,000 along with the bid."
    )
    assert not is_heading("EMD")  # too short to be a section title


def test_sections_follow_headings_across_pages():
    pages = [
        Page(1, "NOTICE INVITING TENDER\nIntro line\n1. EARNEST MONEY DEPOSIT\nEMD is Rs. 16,000."),
        Page(2, "continues on page two\n2. ELIGIBILITY CRITERIA\nThree similar works."),
    ]
    secs = sections(pages)
    assert [s.heading for s in secs] == [
        "NOTICE INVITING TENDER",
        "1. EARNEST MONEY DEPOSIT",
        "2. ELIGIBILITY CRITERIA",
    ]
    emd = secs[1]
    assert {p for p, _ in emd.lines} == {1, 2}


def test_chunks_keep_pages_and_respect_max():
    body = " ".join(["The contractor shall comply with the conditions of contract."] * 40)
    pages = [Page(i, f"{i}. SECTION {chr(64 + i)}\n{body}") for i in range(1, 6)]
    chunks = chunk_pages(pages, target=300, max_tokens=500, overlap=40)
    assert all(c.tokens <= 560 for c in chunks)  # small slack for the repeated heading
    assert chunks[0].page_from == 1 and chunks[-1].page_to == 5
    assert [c.ord for c in chunks] == list(range(len(chunks)))


def test_long_section_is_split_with_overlap_and_heading_repeated():
    sentences = [f"Clause sentence number {i} has some words in it." for i in range(200)]
    pages = [Page(1, "SPECIAL CONDITIONS\n" + " ".join(sentences))]
    chunks = chunk_pages(pages, target=300, max_tokens=400, overlap=40)
    assert len(chunks) > 3
    assert all(c.heading == "SPECIAL CONDITIONS" for c in chunks)
    assert chunks[1].text.startswith("SPECIAL CONDITIONS (continued)")
    last_words_0 = chunks[0].text.split()[-6:]
    assert " ".join(last_words_0) in chunks[1].text  # overlap


def test_small_sections_are_packed_together():
    pages = [Page(1, "\n".join(f"{i}. HEADING {i}\nShort clause {i}." for i in range(1, 10)))]
    chunks = chunk_pages(pages, target=300, max_tokens=800)
    assert len(chunks) == 1


def test_approx_tokens():
    assert approx_tokens("one two three four five six seven eight nine ten") == 13


def test_garbled_devanagari_detection():
    good = "यह निविदा सूचना हिंदी और अंग्रेज़ी दोनों में जारी की गई है। किसी भी विसंगति की स्थिति में"
    bad = "यह न ȡ व ȡ दा सूचना हȯ̑ दी और अंĩेज़ी दोनाȀ मȀ जारी कɺ गइǺ है। क ȡ सी भी व ȡ संगत"
    assert not garbled_devanagari(good)
    assert garbled_devanagari(bad)
    assert not garbled_devanagari("Plain English text with Rs. 16,000 only.")


def test_running_headers_and_footers_are_removed():
    footer = "SYNTHETIC TEST DOCUMENT generated by DocIntel"
    bodies = [
        "The EMD is payable online.",
        "Bids open after the deadline.",
        "Security deposit is recovered.",
        "Disputes go to arbitration.",
    ]
    pages = [Page(i, f"{bodies[i - 1]}\n{footer}\nPage {i} of 4") for i in range(1, 5)]
    text = "\n".join(c.text for c in chunk_pages(pages))
    assert footer not in text and "Page 2 of 4" not in text
    assert all(b in text for b in bodies)
